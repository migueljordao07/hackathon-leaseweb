"""Translate discovered AWS resources into Leaseweb-targeted IaC (WS1).

Contract: tasks/contracts.md (Python API, shared envelope, translated IaC).
Standard library only. Importing this module performs no I/O, network or service start.

Current state: offline stub only (WS1-01). ``stub=True`` writes a synthetic,
non-deployable ``<output_dir>/iac/main.tf`` and reports ``offline_schema``
validation with null exit codes; no tofu is executed. Non-stub calls return an
explicit not-implemented incomplete envelope until WS1-04/WS1-05 land.
"""

from __future__ import annotations

from pathlib import Path

SCHEMA_VERSION = 1

DATA_MAP_KEYS = ("resources", "calls", "buckets", "readiness")
TARGET_KEYS = (
    "target_id",
    "operator",
    "jurisdiction",
    "storage_mode",
    "criteria",
    "prices",
    "explanation",
)

# Provider modes are decided by the human VM gate; anything else stays unselected.
KNOWN_PROVIDER_MODES = frozenset({"leaseweb", "openstack"})

# Template mappings for known resource types (storage depends on the chosen storage_mode).
TEMPLATE_TARGETS = {
    "aws_instance": "compute_instance",
    "aws_security_group": "network_security_group",
}


def _envelope(step: str, mode: str, status: str, checks: list, data: dict, errors: list) -> dict:
    return {
        "schema_version": SCHEMA_VERSION,
        "step": step,
        "mode": mode,
        "status": status,
        "checks": checks,
        "data": data,
        "errors": errors,
    }


def _require_keys(obj: object, keys: tuple, name: str) -> None:
    if not isinstance(obj, dict):
        raise ValueError(f"{name} must be the preceding envelope's data dict")
    if "schema_version" in obj and "data" in obj:
        raise ValueError(f"{name} must be the envelope's data object, not the envelope")
    missing = [k for k in keys if k not in obj]
    if missing:
        raise ValueError(f"{name} missing required keys: {', '.join(missing)}")


def _map_resource(resource: dict, storage_mode: str | None) -> dict:
    rtype = resource.get("type")
    source_id = resource.get("id")
    if not isinstance(source_id, str) or not isinstance(rtype, str):
        raise ValueError("each resource needs string id and type")
    if rtype in TEMPLATE_TARGETS:
        target_type = TEMPLATE_TARGETS[rtype]
    elif rtype == "aws_s3_bucket" and storage_mode:
        target_type = storage_mode
    else:
        return {"source_id": source_id, "target_type": None, "method": "manual",
                "status": "manual",
                "manual_reason": f"no template for {rtype}; AI gap-filling not run in stub"}
    return {"source_id": source_id, "target_type": target_type, "method": "template",
            "status": "mapped", "manual_reason": None}


def _hcl_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _render_stub_main_tf(provider: str, mappings: list[dict]) -> str:
    lines = [
        "# SYNTHETIC, NON-DEPLOYABLE: generated by the SkyShift WS1 offline stub.",
        "# No provider block, no real resources; tofu was not executed.",
        "# Real Leaseweb templates replace this file once the provider mode is approved.",
        "",
        "locals {",
        "  skyshift_synthetic = true",
        f"  skyshift_provider  = {_hcl_string(provider)}",
        "  skyshift_mappings = {",
    ]
    for m in mappings:
        target = m["target_type"] or "manual"
        lines.append(f"    {_hcl_string(m['source_id'])} = {_hcl_string(target)}")
    lines += ["  }", "}", ""]
    return "\n".join(lines)


def translate(data_map: dict, target: dict, *, output_dir: Path, config: dict,
              stub: bool = False) -> dict:
    """Return a translate envelope; writes only ``<output_dir>/iac/main.tf``."""
    _require_keys(data_map, DATA_MAP_KEYS, "data_map")
    _require_keys(target, TARGET_KEYS, "target")
    if not isinstance(output_dir, (Path, str)):
        raise ValueError("output_dir must be a path (run root, normally out)")
    if not isinstance(config, dict):
        raise ValueError("config must be a dict of environment names to values")
    if not isinstance(data_map["resources"], list):
        raise ValueError("data_map.resources must be a list")
    output_dir = Path(output_dir)

    provider_value = config.get("SKYSHIFT_TARGET_PROVIDER")
    provider = provider_value if provider_value in KNOWN_PROVIDER_MODES else "unselected"

    if not stub:
        data = {
            "provider": provider,
            "files": [],
            "resources": [],
            "validation": {"method": "offline_schema", "init_exit": None, "validate_exit": None,
                           "attempts": 0,
                           "diagnostics": ["live translation not implemented yet (WS1-04)"]},
        }
        checks = [{"id": "iac_validated", "status": "incomplete",
                   "detail": "live translation not implemented; no IaC generated"}]
        return _envelope("translate", "live", "incomplete", checks, data,
                         ["live translation not implemented"])

    mappings = [_map_resource(r, target.get("storage_mode")) for r in data_map["resources"]]
    iac_dir = output_dir / "iac"
    iac_dir.mkdir(parents=True, exist_ok=True)
    main_tf = iac_dir / "main.tf"
    main_tf.write_text(_render_stub_main_tf(provider, mappings), encoding="utf-8", newline="\n")

    manual = [m["source_id"] for m in mappings if m["status"] == "manual"]
    data = {
        "provider": provider,
        "files": [main_tf.as_posix()],
        "resources": mappings,
        "validation": {
            "method": "offline_schema",
            "init_exit": None,
            "validate_exit": None,
            "attempts": 0,
            "diagnostics": ["synthetic stub: tofu init/validate not executed; "
                            "file is non-deployable"],
        },
    }
    checks = [
        {"id": "templates_mapped", "status": "incomplete",
         "detail": f"synthetic stub; {len(mappings) - len(manual)} template mappings, "
                   f"{len(manual)} manual"},
        {"id": "iac_validated", "status": "incomplete",
         "detail": "offline_schema only; tofu validate not run"},
    ]
    return _envelope("translate", "stub", "incomplete", checks, data, [])
